  points: assuranceControls.reduce((sum, item) => sum + item.points, 0),
  local: assuranceControls.filter((item) => item.level === "local").reduce((sum, item) => sum + item.points, 0),
  live: assuranceControls.filter((item) => item.level === "live").reduce((sum, item) => sum + item.points, 0),
